/// Resolve a syscall name to its x86_64 number.
pub fn name_to_num(name: &str) -> Option<i64> {
    TABLE.iter().find(|(n, _)| *n == name).map(|(_, v)| *v)
}

/// Resolve a syscall number to a human-readable name, or `sys_<n>`.
pub fn num_to_name(num: i64) -> String {
    TABLE
        .iter()
        .find(|(_, v)| *v == num)
        .map(|(n, _)| n.to_string())
        .unwrap_or_else(|| format!("sys_{num}"))
}
